import { createCipheriv, createDecipheriv, createHash, createHmac, randomBytes, randomUUID, timingSafeEqual } from 'node:crypto'
import jwt from 'jsonwebtoken'
import bcrypt from 'bcryptjs'
import { dbExec, dbGet, dbRun, dbTransaction, isPostgres } from '../db/db.ts'

const CHALLENGE_SECONDS = 300
const SESSION_SECONDS = 8 * 60 * 60
const MAX_ATTEMPTS = 5
const RATE_WINDOW_SECONDS = 300
const BASE32 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'

// RELEASE BLOCKER: there are no backup codes, factor reset, or verified
// out-of-band recovery. Loss of a factor or the encryption key can lock an
// administrator out; a changed/lost key makes stored factors unrecoverable.
// Before enabling, operators need tested identity-verified recovery and securely
// backed-up key custody, plus secure first-admin provisioning. Rejecting the one
// published seed password below does not prove other passwords are uncompromised.
// MFA_ENCRYPTION_KEY must be 32 randomly generated bytes encoded as hex or base64.
// Do not provide a development fallback: losing/changing it makes enrollments inaccessible.
function encryptionKey(): Buffer {
  const value = process.env.MFA_ENCRYPTION_KEY || ''
  let key: Buffer
  if (/^[0-9a-fA-F]{64}$/.test(value)) key = Buffer.from(value, 'hex')
  else if (/^[A-Za-z0-9+/]{43}=$/.test(value)) key = Buffer.from(value, 'base64')
  else throw new Error('MFA unavailable')
  if (key.length !== 32 || new Set(key).size < 16) throw new Error('MFA unavailable')
  return key
}
function challengeKey(): Buffer {
  return createHmac('sha256', encryptionKey()).update('SafeCOI admin MFA pending token v1').digest()
}
function secretKey(): Buffer {
  return createHmac('sha256', encryptionKey()).update('SafeCOI admin MFA AES-256-GCM v1').digest()
}
function encrypt(secret: Buffer, userId: string): string {
  const iv = randomBytes(12)
  const cipher = createCipheriv('aes-256-gcm', secretKey(), iv)
  cipher.setAAD(Buffer.from(`SafeCOI admin MFA v1:${userId}`))
  const encrypted = Buffer.concat([cipher.update(secret), cipher.final()])
  return [iv, cipher.getAuthTag(), encrypted].map(x => x.toString('base64')).join('.')
}
function decrypt(value: string, userId: string): Buffer {
  const parts = value.split('.')
  if (parts.length !== 3) throw new Error('MFA unavailable')
  const [iv, tag, ciphertext] = parts.map(x => Buffer.from(x, 'base64'))
  const decipher = createDecipheriv('aes-256-gcm', secretKey(), iv)
  decipher.setAAD(Buffer.from(`SafeCOI admin MFA v1:${userId}`))
  decipher.setAuthTag(tag)
  return Buffer.concat([decipher.update(ciphertext), decipher.final()])
}
function base32(bytes: Buffer): string {
  let bits = 0, value = 0, out = ''
  for (const byte of bytes) {
    value = (value << 8) | byte
    bits += 8
    while (bits >= 5) { bits -= 5; out += BASE32[(value >>> bits) & 31] }
  }
  if (bits) out += BASE32[(value << (5 - bits)) & 31]
  return out
}

// RFC 6238 (HMAC-SHA1, 30-second step, six decimal digits).
export function totpForCounter(secret: Buffer, counter: number): string {
  const block = Buffer.alloc(8)
  block.writeBigUInt64BE(BigInt(counter))
  const digest = createHmac('sha1', secret).update(block).digest()
  const offset = digest[digest.length - 1] & 15
  return String((digest.readUInt32BE(offset) & 0x7fffffff) % 1_000_000).padStart(6, '0')
}
function matchingCounter(secret: Buffer, code: unknown, now: number): number | null {
  if (typeof code !== 'string' || !/^\d{6}$/.test(code)) return null
  const provided = Buffer.from(code, 'ascii')
  const current = Math.floor(now / 30)
  let match: number | null = null
  // Check the complete window without early-returning on a match.
  for (const counter of [current - 1, current, current + 1]) {
    if (counter >= 0 && timingSafeEqual(provided, Buffer.from(totpForCounter(secret, counter), 'ascii'))) match = counter
  }
  return match
}
function fingerprint(passwordHash: string): string {
  return createHash('sha256').update(passwordHash).digest('hex')
}
const nowSeconds = () => Math.floor(Date.now() / 1000)

let initialized: Promise<void> | undefined
export function initAdminMfa(): Promise<void> {
  if (!initialized) initialized = (async () => {
    await dbExec(`
    CREATE TABLE IF NOT EXISTS admin_mfa_credentials (
      user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, credential_id TEXT NOT NULL, secret_ciphertext TEXT NOT NULL,
      last_counter BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS admin_mfa_challenges (
      id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at BIGINT NOT NULL,
      password_fingerprint TEXT NOT NULL, enrollment_ciphertext TEXT,
      attempts INTEGER NOT NULL DEFAULT 0, consumed INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS admin_mfa_limits (
      user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, attempts INTEGER NOT NULL, window_until BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS admin_mfa_sessions (
      id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, credential_id TEXT NOT NULL,
      password_fingerprint TEXT NOT NULL, expires_at BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS auth_revoked_tokens (
      token_hash TEXT PRIMARY KEY, expires_at BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS auth_password_limits (
      bucket TEXT PRIMARY KEY, attempts INTEGER NOT NULL, window_until BIGINT NOT NULL
    );
  `)
    // Trigger runs in the same transaction as every role/password update, including
    // updates made by legacy routes. It prevents old admin sessions/challenges
    // becoming valid again if a role or password is subsequently restored.
    await dbTransaction(async tx => {
      if (isPostgres) {
        await tx.run('SELECT pg_advisory_xact_lock(728350214)')
        await tx.run(`CREATE OR REPLACE FUNCTION safecoi_revoke_admin_auth() RETURNS trigger AS $$
          BEGIN
            IF OLD.role IS DISTINCT FROM NEW.role OR OLD.password_hash IS DISTINCT FROM NEW.password_hash THEN
              DELETE FROM admin_mfa_sessions WHERE user_id = OLD.id;
              DELETE FROM admin_mfa_challenges WHERE user_id = OLD.id;
            END IF;
            RETURN NEW;
          END; $$ LANGUAGE plpgsql`)
        await tx.run('DROP TRIGGER IF EXISTS safecoi_revoke_admin_auth ON users')
        await tx.run('CREATE TRIGGER safecoi_revoke_admin_auth AFTER UPDATE OF role, password_hash ON users FOR EACH ROW EXECUTE FUNCTION safecoi_revoke_admin_auth()')
      } else {
        await tx.run(`CREATE TRIGGER IF NOT EXISTS safecoi_revoke_admin_auth AFTER UPDATE OF role, password_hash ON users
          WHEN OLD.role IS NOT NEW.role OR OLD.password_hash IS NOT NEW.password_hash
          BEGIN
            DELETE FROM admin_mfa_sessions WHERE user_id = OLD.id;
            DELETE FROM admin_mfa_challenges WHERE user_id = OLD.id;
          END`)
      }
    })
  })().catch(err => { initialized = undefined; throw err })
  return initialized
}

export type MfaUser = { id: string; email: string; password_hash: string; role: string }
type Challenge = { id: string; user_id: string; expires_at: number; enrollment_ciphertext: string | null }

// This is the password explicitly published by this repository's seed script.
// This is not a complete weak/compromised password screen or secure provisioning.
export async function isKnownSeedPassword(hash: string): Promise<boolean> {
  return bcrypt.compare('password123', hash)
}

export async function beginAdminChallenge(user: MfaUser) {
  encryptionKey()
  await initAdminMfa()
  const now = nowSeconds(), id = randomUUID(), expires = now + CHALLENGE_SECONDS
  await dbRun('DELETE FROM admin_mfa_challenges WHERE expires_at <= ?', [now])
  await dbRun('DELETE FROM admin_mfa_sessions WHERE expires_at <= ?', [now])
  const credential = await dbTransaction(async tx => {
    const current = await tx.get<MfaUser>(`SELECT id, email, password_hash, role FROM users WHERE id = ?${isPostgres ? ' FOR UPDATE' : ''}`, [user.id])
    if (!current || current.role !== 'admin' || current.password_hash !== user.password_hash) throw new Error('Authentication unavailable')
    const existing = await tx.get('SELECT credential_id FROM admin_mfa_credentials WHERE user_id = ?', [user.id])
    if (!existing && await isKnownSeedPassword(current.password_hash)) throw new Error('Secure administrator provisioning required')
    await tx.run('INSERT INTO admin_mfa_challenges (id, user_id, expires_at, password_fingerprint) VALUES (?, ?, ?, ?)', [id, user.id, expires, fingerprint(current.password_hash)])
    return existing
  })
  const challenge_token = jwt.sign({ purpose: 'admin_mfa_pending', sub: user.id, jti: id }, challengeKey(), { algorithm: 'HS256', expiresIn: CHALLENGE_SECONDS })
  return { mfa_required: true, enrolled: Boolean(credential), enrollment_required: !credential, challenge_token, expires_in: CHALLENGE_SECONDS }
}

export async function getPendingChallenge(token: string): Promise<{ challenge: Challenge; user: MfaUser } | null> {
  encryptionKey()
  await initAdminMfa()
  let payload: any
  try { payload = jwt.verify(token, challengeKey(), { algorithms: ['HS256'] }) } catch { return null }
  if (payload.purpose !== 'admin_mfa_pending' || typeof payload.sub !== 'string' || typeof payload.jti !== 'string') return null
  const challenge = await dbGet<any>('SELECT * FROM admin_mfa_challenges WHERE id = ? AND user_id = ? AND consumed = 0 AND expires_at > ?', [payload.jti, payload.sub, nowSeconds()])
  if (!challenge) return null
  const user = await dbGet<MfaUser>('SELECT id, email, password_hash, role FROM users WHERE id = ?', [payload.sub])
  if (!user || user.role !== 'admin' || fingerprint(user.password_hash) !== challenge.password_fingerprint) return null
  return { challenge, user }
}

export async function getMfaStatus(userId: string) {
  const credential = await dbGet('SELECT credential_id FROM admin_mfa_credentials WHERE user_id = ?', [userId])
  return { mfa_required: true, enrolled: Boolean(credential), enrollment_required: !credential }
}

export async function startEnrollment(challenge: Challenge, user: MfaUser): Promise<{ secret: string; otpauth_url: string } | null> {
  const encrypted = await dbTransaction(async tx => {
    const active = await tx.get<MfaUser>(`SELECT id, email, password_hash, role FROM users WHERE id = ?${isPostgres ? ' FOR UPDATE' : ''}`, [user.id])
    if (!active || active.role !== 'admin' || active.password_hash !== user.password_hash || await isKnownSeedPassword(active.password_hash)) return null
    const current = await tx.get<any>('SELECT * FROM admin_mfa_challenges WHERE id = ? AND user_id = ? AND consumed = 0 AND expires_at > ?', [challenge.id, user.id, nowSeconds()])
    if (!current || current.password_fingerprint !== fingerprint(active.password_hash) || await tx.get('SELECT credential_id FROM admin_mfa_credentials WHERE user_id = ?', [user.id])) return null
    if (current.enrollment_ciphertext) return current.enrollment_ciphertext as string
    const candidate = encrypt(randomBytes(20), user.id)
    await tx.run('UPDATE admin_mfa_challenges SET enrollment_ciphertext = ? WHERE id = ?', [candidate, challenge.id])
    return candidate
  })
  if (!encrypted) return null
  const secret = base32(decrypt(encrypted, user.id))
  const issuer = 'SafeCOI'
  const otpauth_url = `otpauth://totp/${encodeURIComponent(`${issuer}:${user.email}`)}?secret=${secret}&issuer=${encodeURIComponent(issuer)}&algorithm=SHA1&digits=6&period=30`
  return { secret, otpauth_url }
}

export type VerifyResult = { ok: true; sessionId: string; sessionExpiresIn: number } | { ok: false; limited?: boolean }
export async function verifyAdminCode(challenge: Challenge, user: MfaUser, code: unknown): Promise<VerifyResult> {
  const now = nowSeconds()
  // Atomic per-account fixed window applies across all password-authenticated challenges,
  // preventing unlimited guesses by repeatedly logging in. It expires automatically.
  await dbRun('INSERT INTO admin_mfa_limits (user_id, attempts, window_until) VALUES (?, 0, ?) ON CONFLICT (user_id) DO NOTHING', [user.id, now + RATE_WINDOW_SECONDS])
  const rate = await dbRun(`UPDATE admin_mfa_limits SET attempts = CASE WHEN window_until <= ? THEN 1 ELSE attempts + 1 END,
    window_until = CASE WHEN window_until <= ? THEN ? ELSE window_until END
    WHERE user_id = ? AND (window_until <= ? OR attempts < ?)`, [now, now, now + RATE_WINDOW_SECONDS, user.id, now, MAX_ATTEMPTS])
  if (!rate.changes) return { ok: false, limited: true }
  const attempt = await dbRun('UPDATE admin_mfa_challenges SET attempts = attempts + 1 WHERE id = ? AND user_id = ? AND consumed = 0 AND expires_at > ? AND attempts < ?', [challenge.id, user.id, now, MAX_ATTEMPTS])
  if (!attempt.changes) return { ok: false, limited: true }
  return dbTransaction(async tx => {
    const active = await tx.get<MfaUser>(`SELECT id, email, password_hash, role FROM users WHERE id = ?${isPostgres ? ' FOR UPDATE' : ''}`, [user.id])
    if (!active || active.role !== 'admin' || active.password_hash !== user.password_hash) return { ok: false }
    const current = await tx.get<any>('SELECT * FROM admin_mfa_challenges WHERE id = ? AND user_id = ? AND consumed = 0 AND expires_at > ?', [challenge.id, user.id, nowSeconds()])
    if (!current || current.password_fingerprint !== fingerprint(active.password_hash)) return { ok: false }
    const credential = await tx.get<any>('SELECT * FROM admin_mfa_credentials WHERE user_id = ?', [user.id])
    if (!credential && await isKnownSeedPassword(active.password_hash)) return { ok: false }
    const encrypted = credential?.secret_ciphertext || current.enrollment_ciphertext
    if (!encrypted) return { ok: false }
    const counter = matchingCounter(decrypt(encrypted, user.id), code, nowSeconds())
    if (counter === null) return { ok: false }
    let credentialId: string
    if (credential) {
      credentialId = credential.credential_id
      const used = await tx.run('UPDATE admin_mfa_credentials SET last_counter = ? WHERE user_id = ? AND credential_id = ? AND last_counter < ?', [counter, user.id, credentialId, counter])
      if (!used.changes) return { ok: false }
    } else {
      credentialId = randomUUID()
      await tx.run('INSERT INTO admin_mfa_credentials (user_id, credential_id, secret_ciphertext, last_counter) VALUES (?, ?, ?, ?)', [user.id, credentialId, encrypted, counter])
    }
    await tx.run('UPDATE admin_mfa_challenges SET consumed = 1 WHERE id = ?', [challenge.id])
    const sessionId = randomUUID()
    await tx.run('INSERT INTO admin_mfa_sessions (id, user_id, credential_id, password_fingerprint, expires_at) VALUES (?, ?, ?, ?, ?)', [sessionId, user.id, credentialId, fingerprint(active.password_hash), nowSeconds() + SESSION_SECONDS])
    return { ok: true, sessionId, sessionExpiresIn: SESSION_SECONDS }
  })
}

export async function validateAdminSession(user: MfaUser, sessionId: unknown): Promise<boolean> {
  encryptionKey()
  if (typeof sessionId !== 'string') return false
  await initAdminMfa()
  const row = await dbGet<any>(`SELECT s.id FROM admin_mfa_sessions s JOIN admin_mfa_credentials c
    ON c.user_id = s.user_id AND c.credential_id = s.credential_id
    WHERE s.id = ? AND s.user_id = ? AND s.expires_at > ? AND s.password_fingerprint = ?`,
    [sessionId, user.id, nowSeconds(), fingerprint(user.password_hash)])
  return Boolean(row)
}
